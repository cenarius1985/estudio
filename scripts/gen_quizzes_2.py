async def main():
    async with SessionLocal() as db:
        tema = await db.get(Tema, TEMA)
        print(f"tema: {tema.nombre if tema else '??'}")
        existentes = {
            q.titulo for q in (await db.execute(select(Quiz))).scalars().all()
        }
        nq = np_ = 0
        for titulo, preguntas in QUIZZES:
            if titulo in existentes:
                print(f"  = YA EXISTE, omitido: {titulo}")
                continue
            es_simulacro = "Simulacro" in titulo
            quiz = Quiz(
                titulo=titulo,
                tipo="simulacro" if es_simulacro else "quiz",
                tema_id=TEMA,
                estado="listo",
                duracion_min=25 if es_simulacro else 0,
            )
            db.add(quiz)
            await db.flush()
            for i, (enunciado, alts, correcta, explicacion, archivo) in enumerate(preguntas, 1):
                db.add(Pregunta(
                    quiz_id=quiz.id, n=i, enunciado=enunciado,
                    alternativas=list(alts), correcta=correcta,
                    explicacion=explicacion,
                    cita={"archivo": archivo, "pagina": ""},
                ))
            nq += 1
            np_ += len(preguntas)
            print(f"  + {titulo} ({len(preguntas)} preguntas)")
        await db.commit()
        total = (await db.execute(select(Quiz))).scalars().all()
        print(f"\nListo: {nq} quizzes nuevos, {np_} preguntas. Total en BD: {len(total)} quizzes")

asyncio.run(main())

